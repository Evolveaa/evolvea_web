#!/usr/bin/env node
/**
 * Generates supabase/seed/exercises.sql from content/exercises/*.json.
 * Idempotent seed: ON CONFLICT (slug) keeps the library upgradable.
 * Run scripts/validate-exercises.mjs first.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "content", "exercises");
const OUT = join(ROOT, "supabase", "seed", "exercises.sql");

const esc = (s) => String(s).replace(/'/g, "''");

const rows = [];
for (const file of readdirSync(DIR).filter((f) => f.endsWith(".json"))) {
  const records = JSON.parse(readFileSync(join(DIR, file), "utf8"));
  for (const r of records) {
    rows.push(
      `('${esc(r.slug)}', '${r.domain}', '${r.modality}', '${esc(r.title)}', ` +
        `'${esc(r.summary)}', '${esc(r.parent_guide)}', ${r.difficulty}, ${r.age_min}, ` +
        `${r.age_max}, ${r.duration_minutes}, '${esc(JSON.stringify(r.content))}'::jsonb, true)`,
    );
  }
}

const sql = `-- Built-in exercise library.
-- GENERATED by scripts/build-seed-sql.mjs from content/exercises/*.json — do not edit by hand.
insert into public.exercises
  (slug, domain, modality, title, summary, parent_guide, difficulty, age_min, age_max, duration_minutes, content, is_builtin)
values
${rows.join(",\n")}
on conflict (slug) do update set
  domain = excluded.domain,
  modality = excluded.modality,
  title = excluded.title,
  summary = excluded.summary,
  parent_guide = excluded.parent_guide,
  difficulty = excluded.difficulty,
  age_min = excluded.age_min,
  age_max = excluded.age_max,
  duration_minutes = excluded.duration_minutes,
  content = excluded.content,
  is_builtin = true,
  is_active = true;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, sql);
console.log(`${rows.length} exercises → ${OUT} (${sql.length} bytes)`);
